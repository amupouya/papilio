"""PostgreSQL entities with stored, permuteseq-generated public identities."""

from typing import Any

from sqlalchemy import BigInteger, Computed
from sqlalchemy.exc import CompileError
from sqlalchemy.ext.compiler import compiles
from sqlalchemy.sql import ColumnElement
from sqlalchemy.sql.compiler import SQLCompiler

from papilio.infra.db.schema.entity import IdentifiedEntity, PersistenceEntity
from papilio.infra.db.schema.fields import _field


class _PublicIDExpression(ColumnElement[int]):
    type = BigInteger()
    inherit_cache = False

    def __init__(self, start: int, end: int) -> None:
        self.start = start
        self.capacity = end - start + 1


@compiles(_PublicIDExpression)
def _unsupported_public_id(
    expression: _PublicIDExpression, compiler: SQLCompiler, **kwargs: Any
) -> str:
    raise CompileError("PGPublicIDField requires PostgreSQL and permuteseq")


@compiles(_PublicIDExpression, "postgresql")
def _postgresql_public_id(
    expression: _PublicIDExpression, compiler: SQLCompiler, **kwargs: Any
) -> str:
    identifier = compiler.preparer.quote("id")
    return (
        f"{expression.start} + (range_encrypt_element("
        f"{identifier}, 1, {expression.capacity}, 0) - 1)"
    )


def PGPublicIDField(
    *,
    digits: int | None = None,
    start: int | None = None,
    end: int | None = None,
) -> Any:
    """Declare an immutable stored public ID generated by PostgreSQL.

    Args:
        digits: Exact decimal width, default 10. Exclusive with start/end.
        start: Inclusive positive lower bound of an explicit range.
        end: Inclusive upper bound, no greater than BIGINT's maximum.

    Returns:
        A unique BIGINT field computed from the existing internal ID.

    Raises:
        ValueError: Bounds or width are invalid, mixed, or too small.
        CompileError: The table is compiled for another database backend.
    """
    if start is None and end is None:
        width = 10 if digits is None else digits
        if type(width) is not int or not 1 <= width <= 18:
            raise ValueError("digits must be an integer between 1 and 18")
        start, end = 10 ** (width - 1), 10**width - 1
    elif digits is not None:
        raise ValueError("Choose digits or start/end, not both")
    if (
        type(start) is not int
        or type(end) is not int
        or start < 1
        or end > 2**63 - 1
        or end - start + 1 < 4
    ):
        raise ValueError("start/end must define 4 or more positive BIGINTs")
    return _field(
        BigInteger,
        Computed(_PublicIDExpression(start, end), persisted=True),
        default=None,
        unique=True,
    )


class PGPublicIdentifiedEntity(IdentifiedEntity):
    """Internal primary key plus a PostgreSQL-generated public identity.

    Override public_id with PGPublicIDField for a different width or range.
    Positive internal IDs must not exceed the selected range's capacity.
    """

    public_id: int = PGPublicIDField()

    def to_row(self, *, exclude_unset: bool = True) -> dict[str, Any]:
        """Return insert values, leaving the generated identity to the DB.

        Args:
            exclude_unset: Omit fields not explicitly supplied by the caller.

        Returns:
            Writable column values, excluding public_id.
        """
        values = self.model_dump(
            exclude={"id", "public_id"}, exclude_unset=exclude_unset
        )
        if self.id is not None:
            values["id"] = self.id
        return values

    def to_changes(self) -> dict[str, Any]:
        """Return supplied mutable fields, excluding both identities.

        Args:
            None.

        Returns:
            Explicitly supplied non-identity column values.
        """
        return self.model_dump(exclude={"id", "public_id"}, exclude_unset=True)


class PGPublicPersistenceEntity(PGPublicIdentifiedEntity, PersistenceEntity):
    """PostgreSQL public identities with the standard timestamp fields."""
